#!/usr/bin/env python3
"""attack_dan_ids.py -- try to de-anonymise the second rater's items from committed files.

This is the adversary, kept in the repo so the claim in SECOND-RATER-PROTOCOL.md sec.2 stays
falsifiable rather than asserted. It reconstructs `anon_id -> item_id` for reading H2 using
ONLY things a reader of this repository has: the selection rule and its realised subset
(`DAN_SUBSET`), the id generator (`dan_anon_id`), `worklist.json`, and -- in the version this
attack was written against -- the seed constant that used to sit at the top of
`prepare_dan_session.py`.

Against the code as it stood on 2026-07-26 the attack succeeds completely: the generator is
deterministic, the seed was `SEED_DAN = 20260728`, and `cmd_plan` walked `DAN_SUBSET` in
source order, so position alone gave the item away even without replaying the RNG. The
protocol's claim that Dan's ids "are minted from a different random stream over a different
item list ... so there is no way to line one of your items up against one of his" was
therefore false for anyone holding the repo.

Against the current code it fails: the seed is drawn once into `<dan>/keys/seed.json`, which
lives under the gitignored `dan/` tree, and the item order is drawn from that seed too, so
neither the hex suffix nor the position is predictable.

    python3 attack_dan_ids.py                 # attack a plan built by the CURRENT code
    python3 attack_dan_ids.py --key <path>    # attack an existing key file
"""
import argparse
import json
import os
import pathlib
import random
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

LEGACY_SEED = 20260728          # the constant that used to be `prepare_dan_session.SEED_DAN`
LEGACY_PER_SESSION = 4


def legacy_replay(subset):
    """The reconstruction, in the dozen lines it actually takes.

    Reproduces the pre-amendment `cmd_plan` exactly: one `random.Random(SEED_DAN)`, items
    walked in `DAN_SUBSET` source order, and per item one `randrange(16**4)` for the id
    followed by one `shuffle` of the 32-element tie-break list."""
    rng = random.Random(LEGACY_SEED)
    used, guess = set(), {}
    for si in range(0, len(subset), LEGACY_PER_SESSION):
        for pos, item_id in enumerate(subset[si:si + LEGACY_PER_SESSION], 1):
            while True:
                cand = f"dn{pos:02d}_{rng.randrange(16 ** 4):04x}"
                if cand not in used:
                    used.add(cand)
                    break
            guess[cand] = item_id
            tie = list(range(32))
            rng.shuffle(tie)
    return guess


def truth_from_key(path):
    key = json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
    return {i["anon_id"]: i["item_id"] for s in key["sessions"] for i in s["items"]}


def build_current_plan(tmp):
    """A plan built by the code as it stands now, with a freshly drawn secret seed."""
    env = dict(os.environ, RV_DATA_DAN=str(tmp))
    env.pop("RV_DATA", None)
    r = subprocess.run([sys.executable, str(HERE / "prepare_dan_session.py"), "plan"],
                       cwd=HERE, env=env, capture_output=True, text=True)
    if r.returncode:
        print(r.stdout, r.stderr, file=sys.stderr)
        raise SystemExit("could not build a plan to attack")
    return tmp / "keys" / "plan.key.json"


def report(label, truth, guess):
    hits = sorted(a for a in truth if guess.get(a) == truth[a])
    print(f"\n{label}")
    print(f"  ids in the key : {len(truth)}")
    print(f"  ids the replay reproduced with the right item: {len(hits)}/{len(truth)}")
    for a in sorted(truth):
        g = guess.get(a)
        mark = "CRACKED " if g == truth[a] else "         "
        print(f"    {mark}{a} -> {truth[a]:<20} replay said {g}")
    return len(hits)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--key", help="attack this key file instead of building a fresh plan")
    a = ap.parse_args()

    import prepare_dan_session as pds                                    # noqa: E402
    subset = [r[0] for r in pds.DAN_SUBSET]
    guess = legacy_replay(subset)
    print(f"replayed {len(guess)} ids from committed sources alone "
          f"(seed {LEGACY_SEED}, DAN_SUBSET source order, dan_anon_id)")

    if a.key:
        n = report(f"TARGET: {a.key}", truth_from_key(a.key), guess)
        return 0 if n == 0 else 1

    legacy_key = HERE / "dan" / "keys" / "plan.key.json"
    legacy_hits = None
    if legacy_key.exists():
        t = truth_from_key(legacy_key)
        if json.loads(legacy_key.read_text(encoding="utf-8")).get("seed") == LEGACY_SEED:
            legacy_hits = report(f"BEFORE -- key generated by the old code ({legacy_key})",
                                 t, guess)

    tmp = pathlib.Path(tempfile.mkdtemp(prefix="dan-attack-"))
    try:
        cur_hits = report("AFTER -- key generated by the current code (fresh secret seed)",
                          truth_from_key(build_current_plan(tmp)), guess)
    finally:
        import shutil
        shutil.rmtree(tmp, ignore_errors=True)

    print()
    if legacy_hits is not None:
        print(f"before the amendment: {legacy_hits}/7 recovered -- the mapping was public")
    print(f"after  the amendment: {cur_hits}/7 recovered")
    if cur_hits:
        print("FAIL: the replay still works. The seed or the order is still in the source.")
        return 1
    print("OK: the replay recovers nothing. The seed is not in the repository, and because "
          "the item ORDER comes from it too, an id's position no longer indexes DAN_SUBSET.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
